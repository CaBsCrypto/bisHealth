#[derive(Clone)]
#[contracttype]
pub struct Prescription {
    pub commitment: BytesN<32>,
    pub doctor: Address,
    pub patient_nullifier: BytesN<32>,
    pub policy_hash: BytesN<32>,
    pub is_used: bool,
}

#[derive(Clone)]
#[contracttype]
pub enum DataKey {
    Prescription(BytesN<32>),
    Nullifier(BytesN<32>),
}

#[contractevent(topics = ["trust_leaf_zk_medical", "prescription_issued"])]
#[derive(Clone)]
pub struct PrescriptionIssuedEvent {
    #[topic]
    pub commitment: BytesN<32>,
    #[topic]
    pub doctor: Address,
    #[topic]
    pub patient_nullifier: BytesN<32>,
    pub policy_hash: BytesN<32>,
}

#[contractevent(topics = ["trust_leaf_zk_medical", "prescription_consumed"])]
#[derive(Clone)]
pub struct PrescriptionConsumedEvent {
    #[topic]
    pub commitment: BytesN<32>,
    #[topic]
    pub caller: Address,
    #[topic]
    pub patient_nullifier: BytesN<32>,
}

#[contract]
pub struct TrustLeafZkMedical;

#[contractimpl]
impl TrustLeafZkMedical {
    pub fn issue_prescription(
        env: Env,
        doctor: Address,
        commitment: BytesN<32>,
        patient_nullifier: BytesN<32>,
        policy_hash: BytesN<32>,
    ) {
        doctor.require_auth();
        if env
            .storage()
            .persistent()
            .has(&DataKey::Prescription(commitment.clone()))
        {
            panic!("commitment already exists");
        }
        if env
            .storage()
            .persistent()
            .has(&DataKey::Nullifier(patient_nullifier.clone()))
        {
            panic!("nullifier already registered");
        }

        let prescription = Prescription {
            commitment: commitment.clone(),
            doctor: doctor.clone(),
            patient_nullifier: patient_nullifier.clone(),
            policy_hash: policy_hash.clone(),
            is_used: false,
        };

        env.storage()
            .persistent()
            .set(&DataKey::Prescription(commitment.clone()), &prescription);
        env.storage()
            .persistent()
            .set(&DataKey::Nullifier(patient_nullifier.clone()), &commitment);
        PrescriptionIssuedEvent {
            commitment,
            doctor,
            patient_nullifier,
            policy_hash,
        }
        .publish(&env);
    }

    pub fn verify_and_consume(
        env: Env,
        caller: Address,
        commitment: BytesN<32>,
        proof: Bytes,
        public_inputs_hash: BytesN<32>,
        current_day: u64,
    ) -> bool {
        caller.require_auth();
        let mut prescription: Prescription = env
            .storage()
            .persistent()
            .get(&DataKey::Prescription(commitment.clone()))
            .unwrap();

        if prescription.is_used {
            panic!("prescription already consumed");
        }

        if proof.len() != GROTH16_PROOF_LEN {
            panic!("invalid proof length");
        }

        let expected_hash = Self::public_inputs_hash(
            env.clone(),
            current_day,
            commitment.clone(),
            prescription.patient_nullifier.clone(),
            prescription.policy_hash.clone(),
        );
        if expected_hash != public_inputs_hash {
            panic!("invalid public inputs hash");
        }
        if !Self::verify_groth16(
            &env,
            proof,
            current_day,
            commitment.clone(),
            prescription.patient_nullifier.clone(),
            prescription.policy_hash.clone(),
        ) {
            panic!("invalid proof");
        }

        prescription.is_used = true;
        env.storage()
            .persistent()
            .set(&DataKey::Prescription(commitment.clone()), &prescription);
        PrescriptionConsumedEvent {
            commitment,
            caller,
            patient_nullifier: prescription.patient_nullifier,
        }
        .publish(&env);
        true
    }

    pub fn decode_groth16_proof(env: Env, proof: Bytes) -> (BytesN<64>, BytesN<128>, BytesN<64>) {
        if proof.len() != GROTH16_PROOF_LEN {
            panic!("invalid proof length");
        }

        let a = Self::slice_bytes::<64>(&env, &proof, 0, G1_POINT_LEN);
        let b = Self::slice_bytes::<128>(&env, &proof, G1_POINT_LEN, G2_POINT_LEN);
        let c = Self::slice_bytes::<64>(&env, &proof, G1_POINT_LEN + G2_POINT_LEN, G1_POINT_LEN);
        (a, b, c)
    }

    pub fn public_inputs_hash(
        env: Env,
        current_day: u64,
        commitment: BytesN<32>,
        patient_nullifier: BytesN<32>,
        policy_hash: BytesN<32>,
    ) -> BytesN<32> {
        let payload = Self::serialize_public_inputs(
            &env,
            current_day,
            commitment,
            patient_nullifier,
            policy_hash,
        );
        env.crypto().sha256(&payload).to_bytes()
    }

    pub fn get_prescription(env: Env, commitment: BytesN<32>) -> Prescription {
        env.storage()
            .persistent()
            .get(&DataKey::Prescription(commitment))
            .unwrap()
    }

    fn serialize_public_inputs(
        env: &Env,
        current_day: u64,
        commitment: BytesN<32>,
        patient_nullifier: BytesN<32>,
        policy_hash: BytesN<32>,
    ) -> Bytes {
        let mut payload = Bytes::new(env);
        payload.extend_from_array(&Self::u64_to_field_bytes(current_day));
        payload.append(&commitment.into());
        payload.append(&patient_nullifier.into());
        payload.append(&policy_hash.into());
        payload
    }

    fn verify_groth16(
        env: &Env,
        proof: Bytes,
        current_day: u64,
        commitment: BytesN<32>,
        patient_nullifier: BytesN<32>,
        policy_hash: BytesN<32>,
    ) -> bool {
        let (a_bytes, b_bytes, c_bytes) = Self::decode_groth16_proof(env.clone(), proof);
        let a = Bn254G1Affine::from_bytes(a_bytes);
        let b = Bn254G2Affine::from_bytes(b_bytes);
        let c = Bn254G1Affine::from_bytes(c_bytes);
        let vk_x = Self::compute_vk_x(env, current_day, commitment, patient_nullifier, policy_hash);

        env.crypto().bn254().pairing_check(
            vec![env, a, -Self::vk_alpha_g1(env), -vk_x, -c],
            vec![
                env,
                b,
                Self::vk_beta_g2(env),
                Self::vk_gamma_g2(env),
                Self::vk_delta_g2(env),
            ],
        )
    }

    fn compute_vk_x(
        env: &Env,
        current_day: u64,
        commitment: BytesN<32>,
        patient_nullifier: BytesN<32>,
        policy_hash: BytesN<32>,
    ) -> Bn254G1Affine {
        let public_inputs = [
            Self::u64_to_field_element(env, current_day),
            commitment,
            patient_nullifier,
            policy_hash,
        ];
        let mut acc = Self::vk_ic(env, 0);
        let mut idx = 0;
        while idx < PUBLIC_INPUTS_LEN {
            let scalar = Fr::from_bytes(public_inputs[idx].clone());
            acc = acc + Self::vk_ic(env, idx + 1) * scalar;
            idx += 1;
        }
        acc
    }

    fn vk_alpha_g1(env: &Env) -> Bn254G1Affine {
        Bn254G1Affine::from_bytes(BytesN::from_array(env, &VK_ALPHA_G1))
    }

    fn vk_beta_g2(env: &Env) -> Bn254G2Affine {
        Bn254G2Affine::from_bytes(BytesN::from_array(env, &VK_BETA_G2))
    }

    fn vk_gamma_g2(env: &Env) -> Bn254G2Affine {
        Bn254G2Affine::from_bytes(BytesN::from_array(env, &VK_GAMMA_G2))
    }

    fn vk_delta_g2(env: &Env) -> Bn254G2Affine {
        Bn254G2Affine::from_bytes(BytesN::from_array(env, &VK_DELTA_G2))
    }

    fn vk_ic(env: &Env, index: usize) -> Bn254G1Affine {
        let bytes = match index {
            0 => &VK_IC_0,
            1 => &VK_IC_1,
            2 => &VK_IC_2,
            3 => &VK_IC_3,
            4 => &VK_IC_4,
            _ => panic!("invalid verifying key index"),
        };
        Bn254G1Affine::from_bytes(BytesN::from_array(env, bytes))
    }

    fn u64_to_field_element(env: &Env, value: u64) -> BytesN<32> {
        BytesN::from_array(env, &Self::u64_to_field_bytes(value))
    }

    fn u64_to_field_bytes(value: u64) -> [u8; 32] {
        let mut bytes = [0_u8; 32];
        bytes[24..32].copy_from_slice(&value.to_be_bytes());
        bytes
    }

    fn slice_bytes<const N: usize>(env: &Env, source: &Bytes, start: u32, len: u32) -> BytesN<N> {
        let segment = source.slice(start..start + len);
        let mut out = [0_u8; N];
        segment.copy_into_slice(&mut out);
        BytesN::from_array(env, &out)
    }
}

