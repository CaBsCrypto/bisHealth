fn fixture_proof(env: &Env) -> Bytes {
    let mut proof = Bytes::new(env);
    let segments = [
        (0usize, 64usize),
        (96usize, 128usize),
        (64usize, 96usize),
        (160usize, 192usize),
        (128usize, 160usize),
        (192usize, 256usize),
    ];

    for (start, end) in segments {
        for byte in &FIXTURE_PROOF[start..end] {
            proof.push_back(*byte);
        }
    }
    proof
}

#[test]
fn issues_and_consumes_valid_fixture_proof() {
    let env = Env::default();
    env.mock_all_auths();
    let contract_id = env.register(TrustLeafZkMedical, ());
    let client = TrustLeafZkMedicalClient::new(&env, &contract_id);
    let doctor = Address::generate(&env);
    let commitment = BytesN::from_array(&env, &FIXTURE_COMMITMENT);
    let nullifier = BytesN::from_array(&env, &FIXTURE_NULLIFIER);
    let policy_hash = BytesN::from_array(&env, &FIXTURE_POLICY_HASH);
    let proof = fixture_proof(&env);
    let expected_hash = BytesN::from_array(&env, &FIXTURE_PUBLIC_HASH);

    let derived_hash =
        client.public_inputs_hash(&FIXTURE_CURRENT_DAY, &commitment, &nullifier, &policy_hash);

    client.issue_prescription(&doctor, &commitment, &nullifier, &policy_hash);
    let verified = client.verify_and_consume(
        &doctor,
        &commitment,
        &proof,
        &expected_hash,
        &FIXTURE_CURRENT_DAY,
    );
    let prescription = client.get_prescription(&commitment);

    assert_eq!(derived_hash, expected_hash);
    assert!(verified);
    assert!(prescription.is_used);
    assert_eq!(prescription.policy_hash, policy_hash);
}

#[test]
fn decodes_proof_into_abc_segments() {
    let env = Env::default();
    let contract_id = env.register(TrustLeafZkMedical, ());
    let client = TrustLeafZkMedicalClient::new(&env, &contract_id);
    let proof = fixture_proof(&env);

    let (a, b, c) = client.decode_groth16_proof(&proof);

    assert_eq!(a.to_array()[0], 0x1e);
    assert_eq!(a.to_array()[63], 0xdd);
    assert_eq!(b.to_array()[0], 0x08);
    assert_eq!(b.to_array()[127], 0x22);
    assert_eq!(c.to_array()[0], 0x2c);
    assert_eq!(c.to_array()[63], 0x85);
}

